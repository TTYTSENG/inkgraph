// Manual browser acceptance against disposable data; never connects to port 4317.
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { existsSync,mkdtempSync,rmSync,mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeServer } from '../server.mjs';
import { lightExample } from '../lib/light-import.mjs';

const exe=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','C:/Program Files/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
if(!exe)throw Error('Browser unavailable');
const dir=mkdtempSync(join(tmpdir(),'inkgraph-light-browser-')),app=makeServer({dataPath:dir,port:0});
let browser;
try{
  const project=app.store.save('project',{title:'Light 隔離驗收專案'});
  await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
  browser=await chromium.launch({executablePath:exe,headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
  page.on('pageerror',err=>errors.push(err.message));
  await page.goto(`http://127.0.0.1:${app.server.address().port}/#light`);
  await page.getByRole('heading',{name:'Light 研究成果匯入',exact:true}).waitFor();
  await page.locator('#light-project').selectOption(project.id);
  const b=structuredClone(lightExample);b.sources[0].title='合成驗收文獻，非研究證據';
  b.sources[0].evidence={provider:'隔離測試',readLevel:'abstract',note:'只檢查摘要'};
  b.notes[0].content='合成引用 [@paper1, p. 3]';
  await page.locator('#light-file').setInputFiles({name:'acceptance.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(b))});
  await page.getByRole('button',{name:'預覽成果',exact:true}).click();
  await page.getByRole('button',{name:'確認匯入這批成果',exact:true}).waitFor();
  assert.equal(app.store.list().length,1,'preview must not write');
  await page.locator('[data-light-row="sources:0"]').click();
  await page.locator('#light-status').filter({hasText:'預計新增 1 筆，略過 0 筆重複資料，已移除 2 筆'}).waitFor();
  assert.equal(await page.locator('[data-light-row="annotations:0"]').isDisabled(),true);
  assert.ok((await page.locator('#light-preview').textContent()).includes('請檢查文字引用'));
  assert.equal(app.store.list().length,1);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile removal overflow');
  mkdirSync(new URL('../artifacts/light-import/',import.meta.url),{recursive:true});
  await page.screenshot({path:fileURLToPath(new URL('../artifacts/light-import/selection-mobile.png',import.meta.url)),fullPage:true});
  await page.reload();
  await page.locator('#light-project').selectOption(project.id);
  await page.locator('#light-file').setInputFiles({name:'renamed.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(b))});
  await page.getByRole('button',{name:'預覽成果',exact:true}).click();
  await page.locator('#light-status').filter({hasText:'已接續先前的排除選擇'}).waitFor();
  assert.equal(await page.locator('[data-light-row="annotations:0"]').isDisabled(),true);
  await page.locator('[data-light-row="sources:0"]').click();
  await page.locator('#light-status').filter({hasText:'預計新增 3 筆，略過 0 筆重複資料，已移除 0 筆'}).waitFor();
  await page.locator('[data-light-row="notes:0"]').click();
  await page.locator('[data-light-restore-all]').click();
  await page.locator('#light-status').filter({hasText:'預計新增 3 筆'}).waitFor();
  await page.locator('[data-light-row="annotations:0"]').click();
  await page.locator('#light-status').filter({hasText:'預計新增 2 筆，略過 0 筆重複資料，已移除 1 筆'}).waitFor();
  await page.locator('#light-preview summary').first().click();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
  mkdirSync(new URL('../artifacts/light-import/',import.meta.url),{recursive:true});
  await page.screenshot({path:fileURLToPath(new URL('../artifacts/light-import/mobile.png',import.meta.url)),fullPage:true});
  await page.setViewportSize({width:1280,height:900});
  await page.screenshot({path:fileURLToPath(new URL('../artifacts/light-import/desktop.png',import.meta.url)),fullPage:true});
  await page.getByRole('button',{name:'確認匯入這批成果',exact:true}).click();
  await page.getByRole('status').filter({hasText:'已新增 2 筆成果'}).waitFor();
  assert.equal(app.store.list().length,3);assert.equal(app.store.list().some(r=>r.kind==='annotation'),false);
  const importedSource=app.store.list().find(r=>r.kind==='source'),importedNote=app.store.list().find(r=>r.kind==='note');
  assert.ok(importedNote.content.includes(`[@${importedSource.id}, p. 3]`));
  assert.equal(importedSource.lightEvidence.readLevel,'abstract');
  await page.locator('#light-project').selectOption(project.id);
  await page.locator('#light-file').setInputFiles({name:'acceptance.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(b))});
  await page.getByRole('button',{name:'預覽成果',exact:true}).click();
  await page.locator('#light-status').filter({hasText:'預計新增 1 筆，略過 2 筆'}).waitFor();
  await page.locator('[data-light-row="annotations:0"]').click();
  await page.locator('#light-status').filter({hasText:'預計新增 0 筆，略過 2 筆重複資料，已移除 1 筆'}).waitFor();
  await page.getByRole('button',{name:'讀取批次紀錄'}).click();
  await page.getByRole('button',{name:'撤回此批',exact:true}).click();
  await page.getByRole('button',{name:'確認撤回此批新增資料',exact:true}).click();
  await page.getByRole('status').filter({hasText:'已撤回 2 筆成果'}).waitFor();
  assert.equal(app.store.list().length,1);assert.deepEqual(errors,[]);
  console.log('PASS: browser exclusion, source dependency removal, note warning, individual/bulk restore, selective import, mobile layout, repeat selection, undo; no page errors.');
}finally{
  await browser?.close();app.server.closeAllConnections();await new Promise(resolve=>app.server.close(resolve));app.store.close();rmSync(dir,{recursive:true,force:true});
}
